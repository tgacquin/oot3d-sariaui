#!/usr/bin/env python3
"""Generate guarded EN/FR/ES price spans from the user's USA QM archive.
Only price digits, offsets and fingerprints are emitted, never whole dialogue.
Usage: build-price-patches.py us.qm output.h
"""
from pathlib import Path
import importlib.util
import json
import re
import struct
import sys
spec=importlib.util.spec_from_file_location('messages',Path(__file__).with_name('build-message-patches.py'))
messages=importlib.util.module_from_spec(spec);spec.loader.exec_module(messages)
IDS='''0006 0018 001c 001d 001e 002a 002b 0061 0062 0063 0064 0065 006d
007c 007d 007e 007f 0087 0088 0089 008a 008b 008c 008e 008f 0092 0093 0094 0095 009b 009f
00a0 00a1 00a2 00a3 00a5 00a6 00a9 00aa 00ab 00ac 00b0 00b1 00b2 00b3 00b6 00b7 00b8 00b9 00ba 00bb 00bc
00c1 00ca 00cb 00de 00df 0329 10a0 10a1 10a2 10ca 10cb 10cc 10cd 10ce 10cf 10d4 10d5 10dc 10dd
2025 2031 2038 2039 203d 205b 205e 207e 207f 2085 208b 304f 4053 405c
405e 405f 4060 4061 4062 4063 4064 4065 4066 4067 407b 4093 40b3 500c 5019 506d 506e 600d 6041 6014 6015 6077 7072'''
IDS=set(int(x,16) for x in IDS.split())

def edits(raw):
    # A byte-position map excludes binary command arguments from price matching.
    plain=bytearray();positions=[];i=0
    while i<len(raw):
        if raw[i]==127:
            cmd=raw[i+1];i+=2+messages.ARGS[cmd]
            if cmd==0:break
            if cmd in (1,28):plain.append(32);positions.append(-1)
        else:plain.append(raw[i]);positions.append(i);i+=1
    result=[]
    for match in re.finditer(rb'(?<![\w])(\d+|Ten|five)(?=[ \n-]+(?:Rupees?|rubis|rupias))',plain):
        word=match[1];cost={b'Ten':10,b'five':5}.get(word)
        if cost is None:cost=int(word)
        start,end=match.span(1);at=positions[start];size=positions[end-1]+1-at
        assert size==len(word)
        result.append((at,size,cost))
    return result

def main():
    qm=Path(sys.argv[1]).read_bytes();assert qm[:8]==b'QM\0\0\4\0\0\0'
    catalog=Path(__file__).parents[2]/'src/oot3d/messages/english.json'
    control,_=messages.compile(qm,json.loads(catalog.read_text()))
    control={mid:patches for mid,h,size,patches in control}
    source={}
    for i in range(struct.unpack_from('<I',qm,8)[0]):
        at=16+i*96;mid=struct.unpack_from('<I',qm,at)[0]
        if mid not in IDS:continue
        for slot in (1,5,7):
            off,size=struct.unpack_from('<II',qm,at+16+slot*8)
            raw=qm[off:off+size];source[mid,slot]=[raw]
            if slot==1 and mid in control:
                new=bytearray();cursor=0
                for start,n,insert in control[mid]:new+=raw[cursor:start]+insert;cursor=start+n
                new+=raw[cursor:];source[mid,slot].append(bytes(new))
    assert len(source)==len(IDS)*3
    out=['// SPDX-License-Identifier: GPL-2.0-or-later',
         '// Generated by tools/oot3d/build-price-patches.py. Prices only; no complete game text.',
         '#pragma once','namespace OOT3D::Prices {']
    entries=[];counts=0
    for (mid,slot),variants in sorted(source.items()):
        for v,raw in enumerate(variants):
            changes=edits(raw)
            assert len(changes)==(2 if mid==0x208b else 1),(hex(mid),slot,messages.decode(raw),changes)
            name=f'Price{mid:04X}_{slot}_{v}'
            out.append(f'inline constexpr PriceEdit {name}[]{{')
            for at,size,cost in changes:out.append(f'    {{{at},{size},{cost}}},')
            out.append('};')
            entries.append(f'    {{0x{mid:04X},{slot},0x{messages.fnv(raw):016X}ULL,{len(raw)},{name}}},')
        counts+=len(edits(variants[0]))
    out+=['inline constexpr PriceMessage PriceMessages[]{',*entries,'};',f'inline constexpr unsigned PriceMessageCount={len(source)};','}']
    Path(sys.argv[2]).write_text('\n'.join(out)+'\n')
    print(f'Compiled {len(source)} localized messages, {counts} prices, {len(entries)} guarded variants')
if __name__=='__main__':main()
