#!/usr/bin/env python3
"""Compile locale-specific edits against a user's QM, without embedding whole messages.
Usage: build-message-patches.py us.qm english.json output.h [review.txt]
Controls use {hex-command:hex-arguments}; a newline is QM's line-break command.
"""
import difflib
import json
from pathlib import Path
import re
import struct
import sys

ARGS = {0:0,1:0,2:1,3:2,4:0,5:0,6:1,7:0,8:1,10:1,11:0,12:0,14:5,15:1,
        16:1,17:3,18:0,19:0,20:0,21:0,22:0,23:0,24:1,25:0,26:4,27:6,28:0,
        29:1,30:0,35:1,36:1,37:3,38:1,39:0,40:0,41:0,42:0,43:0}

def decode(b):
    out=[];i=0
    while i<len(b):
        if b[i]!=127:
            end=b.find(b'\x7f',i);end=len(b) if end<0 else end
            out.append(b[i:end].decode('utf8'));i=end;continue
        cmd=b[i+1];n=ARGS[cmd];v=b[i+2:i+2+n];assert len(v)==n
        out.append('\n' if cmd==28 else '{%02x%s}'%(cmd,':'+v.hex() if n else ''))
        i+=2+n
        if cmd==0:
            assert not any(b[i:]);break
    return ''.join(out)

def encode(s):
    out=bytearray()
    for part in re.split(r'(\{[0-9a-f]{2}(?::[0-9a-f]+)?\}|\n)',s):
        if part=='\n':out+=b'\x7f\x1c'
        elif part.startswith('{'):
            bits=part[1:-1].split(':');cmd=int(bits[0],16)
            args=bytes.fromhex(bits[1]) if len(bits)>1 else b''
            assert len(args)==ARGS[cmd];out+=bytes([127,cmd])+args
        else:out+=part.encode('utf8')
    return bytes(out)

def script_controls(s):
    # Typography and control icons can change. Script flow, timing, choices,
    # variables, item-get events and normal/MQ alternatives must stay exact.
    return [x for x in re.findall(r'\{[0-9a-f]{2}(?::[0-9a-f]+)?\}',s)
            if x[1:3] not in ('1d','24')]

def fnv(b):
    h=14695981039346656037
    for x in b:h=((h^x)*1099511628211)&((1<<64)-1)
    return h

def compile(qm,catalog):
    assert qm[:8]==b'QM\0\0\4\0\0\0'
    count=struct.unpack_from('<I',qm,8)[0];slot=catalog['language_slot']
    source={}
    for i in range(count):
        at=16+i*96;mid=struct.unpack_from('<I',qm,at)[0]
        off,size=struct.unpack_from('<II',qm,at+16+slot*8)
        if size:source[mid]=qm[off:off+size]
    compiled=[];review=[]
    for key,entry in catalog['messages'].items():
        mid=int(key,16);old=source[mid];text=decode(old);original=text
        for edit in entry.get('edits',[]):
            assert text.count(edit['find'])==1,(key,edit['find'],text)
            text=text.replace(edit['find'],edit['replace'])
        for edit in catalog.get('common',[]):text=text.replace(edit['find'],edit['replace'])
        assert script_controls(text)==script_controls(original),key
        new=encode(text);assert new!=old,key
        patches=[]
        for op,a,b,c,d in difflib.SequenceMatcher(None,old,new,autojunk=False).get_opcodes():
            if op!='equal':patches.append((a,b-a,new[c:d]))
        compiled.append((mid,fnv(old),len(old),patches))
        review.append('0x'+key+'\n'+text+'\n')
    return compiled,'\n'.join(review)

def main():
    qm=Path(sys.argv[1]).read_bytes();catalog=json.loads(Path(sys.argv[2]).read_text())
    language=catalog['language']
    assert catalog['language_slot']=={'English':1,'French':5,'Spanish':7}[language]
    compiled,review=compile(qm,catalog)
    edit_prefix='' if language=='English' else language
    lines=['// SPDX-License-Identifier: GPL-2.0-or-later',
           '// Generated by tools/oot3d/build-message-patches.py; edit messages/'+Path(sys.argv[2]).name+'.',
           '// Only changed byte spans are embedded; the loaded cartridge supplies all other text.',
           '#pragma once','namespace OOT3D::Messages {']
    for mid,h,size,patches in compiled:
        lines.append('inline constexpr Edit %sEdits%04X[]{'%(edit_prefix,mid))
        for off,n,b in patches:
            escaped=''.join('\\x%02x'%x for x in b)
            lines.append('    {%d,%d,std::string_view{"%s",%d}},'%(off,n,escaped,len(b)))
        lines.append('};')
    lines.append('inline constexpr Message '+language+'[]{')
    for mid,h,size,patches in compiled:
        dependency=catalog['messages'][f'{mid:04X}'].get('requires','None')
        assert dependency in ('None','NaviUp','SongListStart')
        lines.append('    {0x%04X,0x%016XULL,%d,%sEdits%04X,Dependency::%s},'%(mid,h,size,edit_prefix,mid,dependency))
    lines+=['};','}']
    Path(sys.argv[3]).write_text('\n'.join(lines)+'\n')
    if len(sys.argv)>4:Path(sys.argv[4]).write_text(review)
    print('Compiled',len(compiled),'messages for',catalog['language'])
if __name__=='__main__':main()
