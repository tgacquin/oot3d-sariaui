#!/usr/bin/env python3
"""Compile only changed Shard text spans from the user's extracted QM."""
import importlib.util
import json
from pathlib import Path
import sys
spec=importlib.util.spec_from_file_location('compiler',Path(__file__).with_name('build-message-patches.py'))
compiler=importlib.util.module_from_spec(spec);spec.loader.exec_module(compiler)
qm=Path(sys.argv[1]).read_bytes()
catalogs=json.loads(Path(sys.argv[2]).read_text())
lines=['// SPDX-License-Identifier: GPL-2.0-or-later','// Generated by tools/oot3d/build-rumble-text.py.','#pragma once','namespace OOT3D::ShardText {']
entries=[]
for catalog in catalogs:
    compiled,review=compiler.compile(qm,catalog)
    print(review)
    for mid,fingerprint,size,patches in compiled:
        name=f'Edits{catalog["language_slot"]}_{mid:04X}'
        lines.append(f'inline constexpr Messages::Edit {name}[]{{')
        for offset,remove,data in patches:
            escaped=''.join('\\x%02x'%x for x in data)
            lines.append(f'    {{{offset},{remove},std::string_view{{"{escaped}",{len(data)}}}}},')
        lines.append('};')
        entries.append(f'    {{{mid},{catalog["language_slot"]},0x{fingerprint:016X}ULL,{size},{name}}},')
lines+=['inline constexpr Patch Patches[]{']+entries+['};','}']
Path(sys.argv[3]).write_text('\n'.join(lines)+'\n')
