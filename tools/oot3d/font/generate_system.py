"""Redraw sys8 date/time lettering using our existing original font curves."""
import argparse
import struct
from pathlib import Path
from PIL import Image, ImageDraw
from generate import points
from outlines import PATHS

CHARS = '0123456789/:APM.-'
AA = 32

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('qbf', type=Path)
    p.add_argument('--header', required=True, type=Path)
    p.add_argument('--preview', required=True, type=Path)
    args = p.parse_args()
    b = args.qbf.read_bytes()
    assert b[:4] == b'QBF1' and b[12:16] == bytes([8, 8, 16, 4])
    count, sheets = struct.unpack_from('<HH', b, 4)
    assert len(b) == 16 + count * 8 + sheets * 128
    records, runs, cells, originals = [], [], {}, {}
    for c in CHARS:
        record = next(struct.unpack_from('<HH4B', b, 16+i*8) for i in range(count)
                      if struct.unpack_from('<H', b, 16+i*8)[0] == ord(c))
        code, index, left, width, _, _ = record
        native = b[16+count*8+index*128:16+count*8+(index+1)*128]
        signature = 14695981039346656037
        for v in native:
            signature = ((signature ^ v) * 1099511628211) & 0xffffffffffffffff
        # Native pixels supply recognition and placement only. The replacement
        # strokes are our hand-authored curves, not an enlarged native bitmap.
        white = [(i % 8, i // 8) for i,v in enumerate(native) if v == 255]
        x0, y0 = min(x for x,y in white)+.5, min(y for x,y in white)+.5
        x1, y1 = max(x for x,y in white)+.5, max(y for x,y in white)+.5
        paths = [points(path) for path in PATHS[c]]
        xmin, xmax = min(x for ps in paths for x,y in ps), max(x for ps in paths for x,y in ps)
        ymin, ymax = min(y for ps in paths for x,y in ps), max(y for ps in paths for x,y in ps)
        paths = [[((x0+(x-xmin)/max(.001,xmax-xmin)*(x1-x0))*AA,
                   (y0+(y-ymin)/max(.001,ymax-ymin)*(y1-y0))*AA) for x,y in ps] for ps in paths]
        layers = []
        for weight in (2.3, 1.05):
            mask = Image.new('L', (8*AA,16*AA)); draw = ImageDraw.Draw(mask)
            radius = weight*AA/2
            for ps in paths:
                draw.line(ps, fill=255, width=round(weight*AA))
                for x,y in ps:
                    draw.ellipse((x-radius,y-radius,x+radius,y+radius), fill=255)
            # Honor native cropping, so the outline never enters another glyph.
            draw.rectangle((0,0,left*AA-1,16*AA),fill=0) if left else None
            if left+width<8: draw.rectangle(((left+width)*AA,0,8*AA,16*AA),fill=0)
            layers.append(mask.resize((32,64),Image.Resampling.LANCZOS))
        outline, ink = [list(m.getdata()) for m in layers]
        rgba = []
        for a,w in zip(outline,ink):
            a=max(a,w)
            value=round(51+204*w/a) if a else 255
            rgba.extend((value,value,value,a))
        cell=Image.frombytes('RGBA',(32,64),bytes(rgba));cells[c]=cell
        originals[c]=Image.frombytes('RGBA',(8,16),bytes(v for byte in native
            for v in ((byte>>4)*17,)*3+((byte&15)*17,)))
        start=len(runs); pixels=list(zip(*[iter(rgba)]*4)); i=0
        while i<len(pixels):
            j=i+1
            while j<len(pixels) and j-i<255 and pixels[j]==pixels[i]:j+=1
            runs.extend((j-i,*pixels[i]));i=j
        records.append((code,left,width,start,len(runs)-start,signature))
    header='''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by generate_system.py from our hand-authored font curves.
// 32x64 RGBA cells. No native game bitmap data included.
#pragma once
#include <cstdint>
namespace OOT3D::HDFont::SystemArtwork {
struct Record { unsigned code, left, width, offset, size; std::uint64_t native_hash; };
inline constexpr Record Records[] = {
'''
    header+=''.join('    {%d,%d,%d,%d,%d,%dULL},\n'%r for r in records)+'};\n'
    header+='inline constexpr std::uint8_t Runs[] = {\n'
    header+=''.join('    '+','.join(map(str,runs[i:i+30]))+',\n' for i in range(0,len(runs),30))
    args.header.write_text(header+'};\n}\n')
    proof=Image.new('RGBA',(900,210),'#81775e');draw=ImageDraw.Draw(proof)
    for row, images in enumerate((originals,cells)):
        draw.text((10,10+row*100),'Native' if not row else 'HD',fill='white')
        pen=80
        for c in '11/06/26 08:41PM':
            if c==' ':pen+=24;continue
            cell=images[c].resize((40,80),Image.Resampling.NEAREST if not row else Image.Resampling.LANCZOS)
            proof.alpha_composite(cell,(pen,10+row*100));pen+=40
    proof.convert('RGB').save(args.preview)
    print(f'{len(records)} HD system glyphs; {len(runs)} RLE bytes')

if __name__ == '__main__': main()
