# Composed glyphs below transform the hand-drawn curves, not native pixels.
def transform(paths, sx=1, sy=1, dx=0, dy=0):
    import re
    result=[]
    for path in paths:
        tokens=re.findall(r'[MLCZ]|-?\d*\.?\d+',path); axis=0; out=[]
        for t in tokens:
            if t in ('M','L','C','Z'):out.append(t);axis=0
            else:
                v=float(t)*(sx if axis%2==0 else sy)+(dx if axis%2==0 else dy)
                out.append(f'{v:.4f}');axis+=1
        result.append(' '.join(out))
    return result

