"""Generate the heavier HD lettering. Requires Python/Pillow and user's ltn16.qbf.

Native data supplies only codepoints/crop metrics; no native bitmap is embedded.
The shipped header is self-contained; Python is not a build/runtime dependency.
"""
import argparse
import struct
import unicodedata
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from outlines import PATHS, ACCENTS, transform

SCALE=4
AA=32
WEIGHT=1.65

def points(path):
    tokens=re.findall(r'[MLCZ]|-?\d*\.?\d+',path)
    result=[];i=0
    while i<len(tokens):
        cmd=tokens[i];i+=1
        if cmd in ('M','L'):
            result.append((float(tokens[i]),float(tokens[i+1])));i+=2
        elif cmd=='C':
            x0,y0=result[-1]
            x1,y1,x2,y2,x3,y3=map(float,tokens[i:i+6]);i+=6
            for step in range(1,65):
                t=step/64;u=1-t
                result.append((u**3*x0+3*u*u*t*x1+3*u*t*t*x2+t**3*x3,
                               u**3*y0+3*u*u*t*y1+3*u*t*t*y2+t**3*y3))
        elif cmd=='Z':result.append(result[0])
        else:raise ValueError(cmd)
    return result

def shape(c, metrics):
    if c in PATHS:return PATHS[c]
    decomposed=unicodedata.normalize('NFD',c)
    assert len(decomposed)==2 and decomposed[0] in PATHS and decomposed[1] in ACCENTS,repr(c)
    base,accent=decomposed
    left,width=metrics[c];base_left,base_width=metrics[base]
    dx=(width-base_width)/2
    paths=PATHS[base]
    if base=='i':paths=paths[:1]
    # Wider crop on accented I/i leaves room for the mark, not a wider stem.
    paths=transform(paths,dx=dx)
    center=dx+(base_width-1)/2
    dy=-1.6 if base.isupper() and accent not in ('\u0327','\u030a') else 0
    return paths+transform(ACCENTS[accent],dx=center,dy=dy)

def draw(c,metrics,stroke_weight=WEIGHT):
    left,width=metrics[c]
    paths=shape(c,metrics)
    im=Image.new('L',(width*AA,16*AA));d=ImageDraw.Draw(im)
    weight=1.15 if c in '©®ªº¹²³¼½¾' else stroke_weight
    radius=weight*AA/2
    for p in paths:
        ps=[(x*AA,y*AA) for x,y in points(p)]
        d.line(ps,fill=255,width=round(weight*AA))
        for x,y in ps[1:-1]:d.ellipse((x-radius,y-radius,x+radius,y+radius),fill=255)
        if not p.endswith('Z'):
            for x,y in (ps[0],ps[-1]):d.ellipse((x-radius,y-radius,x+radius,y+radius),fill=255)
    cell=Image.new('L',(64,64))
    cell.paste(im.resize((width*SCALE,64),Image.Resampling.LANCZOS),(left*SCALE,0))
    return cell

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('qbf',type=Path)
    parser.add_argument('--header',type=Path,required=True)
    parser.add_argument('--preview',type=Path,required=True)
    parser.add_argument('--weight',type=float,choices=[1.45,1.65],default=WEIGHT)
    args=parser.parse_args()
    b=args.qbf.read_bytes()
    assert b[:4]==b'QBF1' and b[12:15]==bytes([4,16,16])
    count=struct.unpack_from('<H',b,4)[0]
    table=[struct.unpack_from('<HH4B',b,16+i*8) for i in range(count)]
    metrics={chr(c):(l,w) for c,_,l,w,_,_ in table}
    signatures={}
    for c,index,*_ in table:
        signature=14695981039346656037
        for v in b[16+count*8+index*128:16+count*8+(index+1)*128]:
            for a in ((v>>4)*17,(v&15)*17):signature=((signature^a)*1099511628211)&0xffffffffffffffff
        signatures[c]=signature
    chars=[c for c,(l,w) in metrics.items() if w and c!=' ']
    records=[];runs=[];images={}
    for c in chars:
        cell=draw(c,metrics,args.weight);images[c]=cell
        start=len(runs);values=cell.tobytes();i=0
        while i<len(values):
            j=i+1
            while j<len(values) and j-i<255 and values[j]==values[i]:j+=1
            runs.extend((j-i,values[i]));i=j
        records.append((ord(c),*metrics[c],start,len(runs)-start,signatures[ord(c)]))
    header='''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by tools/oot3d/font/generate.py from original hand-drawn curves.
// 64x64 alpha cells, 1.65px native stroke weight. No game bitmaps included.
#pragma once
#include <cstdint>
namespace OOT3D::HDFont::Artwork {
struct Record { std::uint16_t code; std::uint8_t left, width; std::uint32_t offset, size; std::uint64_t native_hash; };
inline constexpr Record Records[] = {
'''
    header+=''.join('    {%d,%d,%d,%d,%d,%dULL},\n'%r for r in records)+'};\n'
    header+='inline constexpr std::uint8_t Runs[] = {\n'
    header+=''.join('    '+','.join(map(str,runs[i:i+32]))+',\n' for i in range(0,len(runs),32))
    header+='};\n} // namespace OOT3D::HDFont::Artwork\n'
    if args.weight==1.45:
        header=header.replace('1.65px','1.45px').replace('::Artwork','::ThinArtwork')
    args.header.write_text(header)
    sheet=Image.new('RGB',(1024,((len(chars)+11)//12)*110),'#141d25');d=ImageDraw.Draw(sheet)
    for i,c in enumerate(chars):
        x=i%12*85;y=i//12*110
        d.text((x+5,y+3),f'U+{ord(c):04X}',fill='#adb9c5')
        sheet.paste('#f5f3ed',(x+8,y+28),images[c])
    args.preview.mkdir(parents=True,exist_ok=True)
    sheet.save(args.preview/'full-alphabet.png')
    # A small proof covers capitals, punctuation, accents, numbers and dialogue.
    texts=['Listen, Link... Take the key. Open the door.',
           'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz 0123456789',
           'Écoute, Link... La forêt a besoin de toi.',
           'Prends cette clé et ouvre la porte.',
           '¡Escucha, Link! El bosque te está esperando.',
           'Toma esta llave y abre la puerta. ¿Sí?',
           'Œuf, garçon, Noël, cœur — « Bonjour ! »']
    proof=Image.new('RGB',(1600,len(texts)*100+40),'#141d25')
    for row,line in enumerate(texts):
        pen=24
        for c in line:
            left,width=metrics[c]
            if c!=' ':
                cell=images[c].crop((left*4,0,(left+width)*4,64))
                proof.paste('#050608',(pen+4,row*100+24),cell.point(lambda a:round(a*.8)))
                proof.paste('#f5f3ed',(pen,row*100+20),cell)
            pen+=(width+1)*4
        assert pen<proof.width,line
    proof.save(args.preview/'language-proof.png')
    print(f'{len(records)} drawn glyphs; {len(runs)} RLE bytes; {args.header}')

if __name__=='__main__':main()
